package com.EduePoa.EP.GeneralLedger.enums;

/**
 * Controlled classification of the business event that produced a journal.
 * <p>
 * Stored as a string ({@code @Enumerated(EnumType.STRING)}) so the persisted
 * value is stable and human-readable. New event types are added by appending a
 * new constant here (never by reusing or renumbering an existing one) and wiring
 * a posting rule in {@code GlPostingRules}; existing journals keep their stored
 * name, so adding a type is backward-compatible.
 */
public enum GlSourceType {
    /** A confirmed student fee receipt (manual entry, M-Pesa STK, C2B/paybill, or bank callback). */
    STUDENT_FEE_RECEIPT,
    /** A student fee refund / correcting cash-out recorded as an EXPENSE finance transaction. */
    STUDENT_FEE_REFUND,
    /** A confirmed transport fee receipt (transport transaction approval). */
    TRANSPORT_FEE_RECEIPT,
    /** Settlement of a supplier accounts-payable balance. */
    SUPPLIER_PAYMENT,
    /** A direct school expense recorded at approval. */
    EXPENSE_PAYMENT,
    /** A monthly payroll run accrual (expense + statutory/net-pay liabilities). */
    PAYROLL_RUN,
    /** A manually posted journal (reserved; manual posting endpoint deferred for release 1). */
    MANUAL,
    /** A reversal counter-journal generated by the maker-checker reversal workflow. */
    REVERSAL
}
